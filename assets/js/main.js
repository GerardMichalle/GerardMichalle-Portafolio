document.querySelectorAll("[data-slider]").forEach((slider) => {
  const track = slider.querySelector(".gallery-slider-track");
  const slides = [...track.children];
  const dots = [...slider.querySelectorAll(".gallery-slider-dot")];
  const prevButton = slider.querySelector(".gallery-slider-prev");
  const nextButton = slider.querySelector(".gallery-slider-next");
  const isControl = (target) =>
    target.closest(".gallery-slider-arrow, .gallery-slider-dot");
  let index = 0;

  function goTo(newIndex) {
    index = (newIndex + slides.length) % slides.length;
    track.style.transform = `translateX(-${index * 100}%)`;
    dots.forEach((dot, dotIndex) =>
      dot.classList.toggle("is-active", dotIndex === index),
    );
  }

  prevButton?.addEventListener("click", (event) => {
    event.stopPropagation();
    goTo(index - 1);
  });
  nextButton?.addEventListener("click", (event) => {
    event.stopPropagation();
    goTo(index + 1);
  });
  dots.forEach((dot, dotIndex) => {
    dot.addEventListener("click", (event) => {
      event.stopPropagation();
      goTo(dotIndex);
    });
  });

  let dragStartX = null;

  slider.addEventListener("pointerdown", (event) => {
    if (isControl(event.target)) return;
    dragStartX = event.clientX;
  });
  slider.addEventListener("pointerup", (event) => {
    if (dragStartX === null || isControl(event.target)) return;
    const delta = event.clientX - dragStartX;
    dragStartX = null;
    if (Math.abs(delta) < 12) {
      openLightbox(
        slides.map((slide) => ({ src: slide.src, alt: slide.alt })),
        index,
        getLightboxInfo(slider.closest(".gallery-card")),
      );
      return;
    }
    if (Math.abs(delta) < 40) return;
    goTo(delta < 0 ? index + 1 : index - 1);
  });
  slider.addEventListener("pointerleave", () => {
    dragStartX = null;
  });
});

function initGalleryDescriptionToggles() {
  const t = translations[currentLanguage] || translations.es;
  const paragraphs = document.querySelectorAll(
    "#mis-proyectos .gallery-card-body p:not(.gallery-card-subtitle)",
  );

  paragraphs.forEach((p) => {
    if (p.scrollHeight - p.clientHeight <= 1) return;

    const toggle = document.createElement("button");
    toggle.type = "button";
    toggle.className = "gallery-card-desc-toggle";
    toggle.textContent = t.readMore;
    toggle.setAttribute("aria-expanded", "false");
    toggle.setAttribute("data-hoverable", "");

    let expanded = false;
    let transitioning = false;

    toggle.addEventListener("click", () => {
      if (transitioning) return;
      transitioning = true;
      expanded = !expanded;
      toggle.setAttribute("aria-expanded", String(expanded));
      toggle.textContent = expanded ? t.readLess : t.readMore;

      if (expanded) {
        p.style.maxHeight = p.clientHeight + "px";
        p.classList.add("is-expanded");
        const fullHeight = p.scrollHeight;
        requestAnimationFrame(() => {
          requestAnimationFrame(() => {
            p.style.maxHeight = fullHeight + "px";
          });
        });
      } else {
        p.style.maxHeight = p.scrollHeight + "px";
        void p.offsetHeight;
        p.classList.remove("is-expanded");
        const collapsedHeight = p.clientHeight;
        p.classList.add("is-expanded");
        requestAnimationFrame(() => {
          requestAnimationFrame(() => {
            p.style.maxHeight = collapsedHeight + "px";
          });
        });
      }
    });

    p.addEventListener("transitionend", (event) => {
      if (event.propertyName !== "max-height") return;
      transitioning = false;
      if (expanded) {
        p.style.maxHeight = "none";
      } else {
        p.classList.remove("is-expanded");
        p.style.maxHeight = "";
      }
    });

    p.insertAdjacentElement("afterend", toggle);
  });
}

if (document.fonts?.ready) {
  document.fonts.ready.then(initGalleryDescriptionToggles);
} else {
  initGalleryDescriptionToggles();
}
